const lineRegex = /^(\d+)\s+([A-Za-z'-]+)\s+([\d,]+)\s+([A-Za-z'-]+)\s+([\d,]+)$/;

for (const line of lines) {
  const match = line.match(lineRegex);
  if (!match) {
    throw new Error(`Failed to parse line: "${line}"`);
  }

  const rank = parseInt(match[1], 10);
  const maleName = match[2];
  const maleCount = parseInt(match[3].replace(/,/g, ""), 10);
  const femaleName = match[4];
  const femaleCount = parseInt(match[5].replace(/,/g, ""), 10);

  maleRecords.push({
    year: 2025,
    sex: "M",
    name: maleName,
    rank,
    birthCount: maleCount,
    birthSharePercentage: null,
  });

  femaleRecords.push({
    year: 2025,
    sex: "F",
    name: femaleName,
    rank,
    birthCount: femaleCount,
    birthSharePercentage: null,
  });
}

if (maleRecords.length !== 1000 || femaleRecords.length !== 1000) {
  throw new Error(`Expected 1000 male and 1000 female rows, got ${maleRecords.length} and ${femaleRecords.length}`);
}

